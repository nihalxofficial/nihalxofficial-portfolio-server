/**
 * Transactional email markup for the contact inbox.
 *
 * Email clients ignore most CSS, so this stays deliberately old-school: nested
 * tables, inline styles and no external assets. The palette mirrors the site so
 * a message from the portfolio is recognisable at a glance, in both the dark
 * and the light reading mode of the client.
 */

const INK = "#0a1420";
const MUTED = "#8ea3bb";
const TEXT = "#e6f1ff";
const ACCENT = "#22d3ee";
const ACCENT_SOFT = "#38bdf8";
const PANEL = "#0d1b2c";
const LINE = "#1d3049";

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

/** Plain-text alternative, so nothing is lost in a text-only client. */
function plainLines(rows: Array<[string, string]>, body: string): string {
  const head = rows.map(([label, value]) => `${label}: ${value}`).join("\n");
  return `${head}\n\n${body}\n`;
}

function shell(brand: string, title: string, subtitle: string, sections: string): string {
  return `
  <div style="background:#05090f;padding:28px 16px;font-family:'Segoe UI',Inter,Arial,sans-serif">
    <table role="presentation" cellpadding="0" cellspacing="0" width="100%" style="max-width:640px;margin:0 auto">
      <tr>
        <td style="background:${PANEL};border:1px solid ${LINE};border-radius:16px;overflow:hidden">
          <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
            <tr>
              <td style="padding:22px 26px;background:#071627">
                <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
                  <tr>
                    <td style="font-size:11px;letter-spacing:2.4px;text-transform:uppercase;color:${ACCENT};font-weight:700">
                      ${escapeHtml(brand)}
                    </td>
                    <td align="right" style="font-size:11px;letter-spacing:1.6px;text-transform:uppercase;color:${MUTED}">
                      control centre
                    </td>
                  </tr>
                  <tr>
                    <td colspan="2" style="padding-top:12px;font-size:21px;line-height:26px;font-weight:700;color:${TEXT}">
                      ${title}
                    </td>
                  </tr>
                  <tr>
                    <td colspan="2" style="padding-top:6px;font-size:13px;line-height:19px;color:${MUTED}">
                      ${subtitle}
                    </td>
                  </tr>
                </table>
              </td>
            </tr>
            <tr><td style="height:1px;background:linear-gradient(90deg,${ACCENT},${ACCENT_SOFT},transparent)"></td></tr>
            ${sections}
          </table>
        </td>
      </tr>
      <tr>
        <td style="padding:14px 6px 0;font-size:11px;line-height:17px;color:#5c748f;text-align:center">
          Generated by the portfolio contact system · this inbox is backed by MongoDB, so nothing is lost
        </td>
      </tr>
    </table>
  </div>`;
}

function metaRow(label: string, value: string, last = false): string {
  return `
  <tr>
    <td style="padding:9px 0;${last ? "" : `border-bottom:1px solid ${LINE};`}font-size:12px;line-height:18px">
      <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
        <tr>
          <td width="120" style="color:${MUTED};text-transform:uppercase;letter-spacing:1.2px;font-size:10.5px;padding-right:12px">${escapeHtml(label)}</td>
          <td style="color:${TEXT};font-weight:600">${value}</td>
        </tr>
      </table>
    </td>
  </tr>`;
}

/** Sender details + the message, quoted on a panel with an accent rail. */
export function newMessageEmail(input: {
  name: string;
  email: string;
  subject: string;
  message: string;
  location?: string;
  dashboardUrl?: string;
  receivedAt?: string;
  /** Wordmark in the email header — falls back to the site name. */
  brand?: string;
}): { subject: string; html: string; text: string } {
  const rows: Array<[string, string]> = [
    ["Name", escapeHtml(input.name)],
    [
      "Email",
      `<a href="mailto:${escapeHtml(input.email)}" style="color:${ACCENT};text-decoration:none">${escapeHtml(input.email)}</a>`,
    ],
    ["Subject", escapeHtml(input.subject || "Portfolio inquiry")],
  ];

  if (input.location) rows.push(["Location", escapeHtml(input.location)]);
  if (input.receivedAt) rows.push(["Received", escapeHtml(input.receivedAt)]);

  const metaTable = `<table role="presentation" cellpadding="0" cellspacing="0" width="100%">${rows
    .map(([label, value], index) => metaRow(label, value, index === rows.length - 1))
    .join("")}</table>`;

  const body = `
    <tr>
      <td style="padding:22px 26px">
        ${metaTable}
      </td>
    </tr>
    <tr>
      <td style="padding:0 26px 24px">
        <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
          <tr>
            <td style="width:3px;background:${ACCENT};border-radius:3px"></td>
            <td style="padding:16px 18px;background:${INK};border:1px solid ${LINE};border-radius:0 12px 12px 0">
              <p style="margin:0;font-size:14px;line-height:23px;color:${TEXT};white-space:pre-wrap">${escapeHtml(input.message)}</p>
            </td>
          </tr>
        </table>
      </td>
    </tr>
    <tr>
      <td style="padding:0 26px 26px">
        <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
          <tr>
            <td>
              <a href="mailto:${escapeHtml(input.email)}?subject=${encodeURIComponent(
                `Re: ${input.subject || "your message"}`,
              )}" style="display:inline-block;padding:11px 18px;background:linear-gradient(135deg,${ACCENT},${ACCENT_SOFT});border-radius:10px;color:#031018;font-size:13px;font-weight:700;text-decoration:none">Reply to ${escapeHtml(input.name.split(" ")[0] || input.name)}</a>
            </td>
            ${
              input.dashboardUrl
                ? `<td align="right"><a href="${escapeHtml(
                    input.dashboardUrl,
                  )}" style="display:inline-block;padding:11px 16px;border:1px solid ${LINE};border-radius:10px;color:${ACCENT};font-size:13px;font-weight:600;text-decoration:none">Open inbox</a></td>`
                : ""
            }
          </tr>
        </table>
      </td>
    </tr>`;

  return {
    subject: `${input.name} — ${input.subject || "Portfolio inquiry"}`,
    html: shell(
      input.brand || "portfolio",
      "New message in your inbox",
      "A visitor reached out through the contact form",
      body,
    ),
    text: plainLines(
      [
        ["From", `${input.name} <${input.email}>`],
        ["Subject", input.subject || "Portfolio inquiry"],
        ...(input.location ? [["Location", input.location] as [string, string]] : []),
      ],
      input.message,
    ),
  };
}

/** The answer the admin sends from the dashboard, delivered to the visitor. */
export function replyEmail(input: {
  to: string;
  name: string;
  subject: string;
  body: string;
  originalMessage: string;
  siteName?: string;
  siteUrl?: string;
  brand?: string;
}): { subject: string; html: string; text: string } {
  const firstName = input.name.split(" ")[0] || input.name;

  const sections = `
    <tr>
      <td style="padding:24px 26px 6px">
        <p style="margin:0 0 14px;font-size:15px;line-height:23px;color:${TEXT}">Hi ${escapeHtml(firstName)},</p>
        <p style="margin:0;font-size:14px;line-height:23px;color:${TEXT};white-space:pre-wrap">${escapeHtml(input.body)}</p>
      </td>
    </tr>
    <tr>
      <td style="padding:22px 26px 26px">
        <p style="margin:0 0 8px;font-size:10.5px;letter-spacing:1.6px;text-transform:uppercase;color:${MUTED}">Your message</p>
        <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
          <tr>
            <td style="width:3px;background:${LINE}"></td>
            <td style="padding:6px 0 6px 16px;font-size:13px;line-height:21px;color:${MUTED};white-space:pre-wrap">
              ${escapeHtml(input.originalMessage)}
            </td>
          </tr>
        </table>
      </td>
    </tr>
    ${
      input.siteUrl
        ? `<tr>
      <td style="padding:0 26px 26px">
        <table role="presentation" cellpadding="0" cellspacing="0" width="100%">
          <tr>
            <td style="border-top:1px solid ${LINE};padding-top:18px">
              <p style="margin:0;font-size:12px;line-height:20px;color:${MUTED}">
                ${escapeHtml(input.siteName || "Md. Nihal Uddin Bijoy")} ·
                <a href="${escapeHtml(input.siteUrl)}" style="color:${ACCENT};text-decoration:none">${escapeHtml(input.siteUrl.replace(/^https?:\/\//, ""))}</a>
              </p>
            </td>
          </tr>
        </table>
      </td>
    </tr>`
        : ""
    }`;

  return {
    subject: input.subject,
    html: shell(input.brand || input.siteName || "portfolio", input.subject, `${input.siteName || "Md. Nihal Uddin Bijoy"} replied to your message`, sections),
    text: `${input.body}\n\n— ${input.siteName || "Md. Nihal Uddin Bijoy"}${
      input.siteUrl ? `\n${input.siteUrl}` : ""
    }

Your message:
${input.originalMessage}
`,
  };
}
